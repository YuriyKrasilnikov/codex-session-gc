from __future__ import annotations

import base64
import csv
import hashlib
import json
import os
import stat
import tarfile
import tomllib
import zipfile
from dataclasses import dataclass
from email.parser import BytesParser
from enum import StrEnum
from importlib.metadata import version
from importlib.util import cache_from_source
from io import TextIOWrapper
from pathlib import Path, PurePosixPath
from typing import TYPE_CHECKING

from hatchling.builders.sdist import SdistBuilder
from hatchling.builders.wheel import WheelBuilder

if TYPE_CHECKING:
    from collections.abc import Iterator
    from typing import IO

HATCH_VERSION = "1.32.4"
_HASH_CHUNK_BYTES = 1024 * 1024
_RECORD_COLUMNS = 3
_INSTALLER_METADATA = ("RECORD", "INSTALLER", "REQUESTED", "direct_url.json", "uv_cache.json")
_BYTECODE_OPTIMIZATIONS = ("", "1", "2")


class ArtifactError(ValueError):
    """An artifact differs from its selected source or declared generated metadata."""


class Target(StrEnum):
    """Supported standard distribution targets of the qualified Python builder."""

    WHEEL = "wheel"
    SDIST = "sdist"


@dataclass(frozen=True, slots=True)
class MappedFile:
    """One distributed file and its source coordinates or generated byte identity."""

    source: Path | None
    relative_path: str | None
    distribution_path: str
    sha256: str
    size: int


@dataclass(frozen=True, slots=True)
class SourceMap:
    """Complete file identities for one standard distribution, excluding its RECORD."""

    project_id: str
    target: Target
    files: tuple[MappedFile, ...]
    record_path: str | None

    @property
    def digest(self) -> str:
        """Return a portable identity without exposing the absolute checkout path."""
        value = [
            {
                "source_relative": item.relative_path,
                "distribution_path": item.distribution_path,
                "sha256": item.sha256,
                "bytes": item.size,
            }
            for item in self.files
        ]
        return hashlib.sha256(
            json.dumps(value, sort_keys=True, separators=(",", ":")).encode()
        ).hexdigest()


def _require(message: str, *, condition: bool) -> None:
    if not condition:
        raise ArtifactError(message)


def _safe_name(name: str) -> bool:
    path = PurePosixPath(name)
    return (
        bool(path.parts)
        and not path.is_absolute()
        and ".." not in path.parts
        and path.as_posix() == name.rstrip("/")
    )


def _builder(root: Path, target: Target) -> WheelBuilder | SdistBuilder:
    configuration = tomllib.loads((root / "pyproject.toml").read_text())
    system = configuration["build-system"]
    _require(
        "Source mapping requires the pinned Hatch build backend.",
        condition=version("hatchling") == HATCH_VERSION
        and system["requires"] == [f"hatchling=={HATCH_VERSION}"]
        and system["build-backend"] == "hatchling.build"
        and not system.get("backend-path"),
    )
    hatch = configuration.get("tool", {}).get("hatch", {})
    build = hatch.get("build", {})
    selected = build.get("targets", {}).get(target.value, {})
    _require(
        "Source mapping requires static metadata and unhooked standard builds.",
        condition=not configuration["project"].get("dynamic")
        and not build.get("hooks")
        and not selected.get("hooks")
        and not hatch.get("metadata", {}).get("hooks"),
    )
    _require(
        "Additional generated distribution surfaces require qualified source mapping.",
        condition=not any(
            selected.get(field)
            for field in (
                "shared-data",
                "shared-scripts",
                "extra-metadata",
                "sbom-files",
                "support-legacy",
            )
        ),
    )
    if target is Target.WHEEL:
        return WheelBuilder(str(root))
    _require("Unsupported source distribution target.", condition=target is Target.SDIST)
    return SdistBuilder(str(root))


def _source(root: Path, path: Path, relative: str, distributed: str) -> MappedFile:
    _require(
        "A distributed source must be a regular file inside the current source checkout.",
        condition=bool(relative)
        and path.is_absolute()
        and path.is_relative_to(root)
        and path.resolve() == path
        and path.is_file()
        and _safe_name(distributed),
    )
    with path.open("rb") as stream:
        before = os.fstat(stream.fileno())
        digest = _stream_digest(stream)
        after = path.stat()
        _require(
            "A source file changed during mapping.",
            condition=(
                before.st_dev,
                before.st_ino,
                before.st_size,
                before.st_mtime_ns,
                before.st_ctime_ns,
            )
            == (after.st_dev, after.st_ino, after.st_size, after.st_mtime_ns, after.st_ctime_ns),
        )
    return MappedFile(path, relative, distributed, digest, before.st_size)


def _stream_digest(stream: IO[bytes]) -> str:
    digest = hashlib.sha256()
    while block := stream.read(_HASH_CHUNK_BYTES):
        digest.update(block)
    return digest.hexdigest()


def _generated(name: str, data: bytes) -> MappedFile:
    return MappedFile(None, None, name, hashlib.sha256(data).hexdigest(), len(data))


def source_map(root: Path, target: Target) -> SourceMap:
    """Use Hatch's file enumeration and current static metadata without building an artifact."""
    root = root.resolve()
    builder = _builder(root, target)
    build_data = builder.get_default_build_data()
    builder.set_build_data_defaults(build_data)
    with builder.config.set_build_data(build_data):
        files = [
            _source(root, Path(item.path), item.relative_path, item.distribution_path)
            for item in builder.recurse_included_files()
        ]
    metadata = builder.config.core_metadata_constructor(builder.metadata).encode()
    project_id = builder.artifact_project_id
    record = None
    if isinstance(builder, WheelBuilder):
        prefix = f"{project_id}.dist-info/"
        files.append(_generated(prefix + "METADATA", metadata))
        _require(
            "The current source requires a qualified generic Python wheel.",
            condition=builder.get_default_tag() == "py3-none-any",
        )
        archive_metadata = (
            "Wheel-Version: 1.0\n"
            f"Generator: hatchling {HATCH_VERSION}\n"
            "Root-Is-Purelib: true\nTag: py3-none-any\n"
        ).encode()
        files.append(_generated(prefix + "WHEEL", archive_metadata))
        entry_points = builder.construct_entry_points_file()
        if entry_points:
            files.append(_generated(prefix + "entry_points.txt", entry_points.encode()))
        files.extend(
            _source(root, root / relative, relative, prefix + "licenses/" + relative)
            for relative in builder.metadata.core.license_files
        )
        record = prefix + "RECORD"
    else:
        files.append(_generated("PKG-INFO", metadata))
    names = [item.distribution_path for item in files]
    _require(
        "Source mapping contains duplicate distribution paths.",
        condition=len(names) == len(set(names)) and record not in names,
    )
    return SourceMap(
        project_id, target, tuple(sorted(files, key=lambda item: item.distribution_path)), record
    )


def wheel_members(archive: zipfile.ZipFile) -> dict[str, zipfile.ZipInfo]:
    """Require distinct safe regular wheel members before any content is consumed."""
    names = archive.namelist()
    _require(
        "Duplicate, linked or unsafe wheel members.",
        condition=len(names) == len(set(names))
        and all(
            _safe_name(info.filename) and not stat.S_ISLNK(info.external_attr >> 16)
            for info in archive.infolist()
        ),
    )
    return {info.filename: info for info in archive.infolist() if not info.is_dir()}


def verify_record(wheel: Path) -> None:
    """Check every wheel member against its RECORD hash and byte length."""
    with zipfile.ZipFile(wheel) as archive:
        members = wheel_members(archive)
        _record_matches(archive, members)


def _record_rows(stream: IO[str]) -> Iterator[list[str]]:
    try:
        yield from csv.reader(stream)
    except csv.Error as error:
        message = f"Wheel RECORD is malformed: {error}"
        raise ArtifactError(message) from error


def _record_matches(
    archive: zipfile.ZipFile, members: dict[str, zipfile.ZipInfo]
) -> dict[str, tuple[str, int]]:
    files = set(members)
    records = [name for name in files if name.endswith(".dist-info/RECORD")]
    _require("Expected one wheel RECORD.", condition=len(records) == 1)
    record = records[0]
    metadata_root = record.rsplit("/", 1)[0]
    _require(
        "Wheel identity metadata is missing.",
        condition=(f"{metadata_root}/WHEEL" in files and f"{metadata_root}/METADATA" in files),
    )
    fields = BytesParser().parsebytes(archive.read(f"{metadata_root}/WHEEL"))
    _require(
        "Expected a generic pure-Python wheel.",
        condition=(
            fields["Wheel-Version"] == "1.0"
            and fields["Root-Is-Purelib"] == "true"
            and fields.get_all("Tag") == ["py3-none-any"]
        ),
    )
    seen = set()
    identities: dict[str, tuple[str, int]] = {}
    with (
        archive.open(record) as raw,
        TextIOWrapper(raw, encoding="utf-8", newline="") as stream,
    ):
        for row in _record_rows(stream):
            _require("Invalid wheel RECORD row.", condition=len(row) == _RECORD_COLUMNS)
            name, declared_hash, declared_size = row
            _require(
                "Unlisted or duplicate RECORD entry.",
                condition=name in files and name not in seen,
            )
            seen.add(name)
            if name == record:
                _require(
                    "RECORD cannot hash itself.", condition=declared_hash == declared_size == ""
                )
                continue
            info = archive.getinfo(name)
            _require(
                "Wheel member is a symbolic link.",
                condition=not stat.S_ISLNK(info.external_attr >> 16),
            )
            with archive.open(name) as source:
                observed_hash = _stream_digest(source)
            size = info.file_size
            identities[name] = observed_hash, size
            actual = "sha256=" + base64.urlsafe_b64encode(
                bytes.fromhex(observed_hash)
            ).decode().rstrip("=")
            _require(
                f"Wheel RECORD differs for {name}.",
                condition=declared_hash == actual and declared_size == str(size),
            )
    _require("Wheel files are missing from RECORD.", condition=seen == files)

    return identities


def verify_wheel(wheel: Path, root: Path) -> SourceMap:
    """Reject missing, extra or changed wheel payload despite self-consistent artifact hashes."""
    selected = source_map(root, Target.WHEEL)
    with zipfile.ZipFile(wheel) as archive:
        members = wheel_members(archive)
        expected = {item.distribution_path for item in selected.files}
        if selected.record_path is not None:
            expected.add(selected.record_path)
        _require(
            "Wheel file set differs from the current source.", condition=set(members) == expected
        )
        for item in selected.files:
            _require(
                f"Wheel payload size differs from the current source: {item.distribution_path}",
                condition=members[item.distribution_path].file_size == item.size,
            )
        identities = _record_matches(archive, members)
        for item in selected.files:
            _require(
                f"Wheel payload differs from the current source: {item.distribution_path}",
                condition=identities[item.distribution_path] == (item.sha256, item.size),
            )
    return selected


def verify_sdist(sdist: Path, root: Path) -> SourceMap:
    """Require all selected source-distribution bytes and only declared generated metadata."""
    selected = source_map(root, Target.SDIST)
    with tarfile.open(sdist, "r:gz") as archive:
        names = archive.getnames()
        _require(
            "Duplicate, linked or unsafe source-distribution members.",
            condition=len(names) == len(set(names))
            and all(
                _safe_name(item.name)
                and (item.isdir() or item.isfile())
                and PurePosixPath(item.name).parts[0] == selected.project_id
                for item in archive.getmembers()
            ),
        )
        members = {
            PurePosixPath(item.name).relative_to(selected.project_id).as_posix(): item
            for item in archive.getmembers()
            if item.isfile()
        }
        _require(
            "Source distribution file set differs from the current source.",
            condition=set(members) == {item.distribution_path for item in selected.files},
        )
        for item in selected.files:
            _require(
                f"Source distribution differs from the current source: {item.distribution_path}",
                condition=members[item.distribution_path].size == item.size,
            )
            stream = archive.extractfile(members[item.distribution_path])
            if stream is None:
                message = "A selected source-distribution file is unavailable."
                raise ArtifactError(message)
            with stream:
                actual = _stream_digest(stream)
            _require(
                f"Source distribution differs from the current source: {item.distribution_path}",
                condition=members[item.distribution_path].size == item.size
                and actual == item.sha256,
            )
    return selected


def _installed_files(root: Path, prefixes: set[str]) -> set[str]:
    observed: set[str] = set()
    for prefix in prefixes:
        path = root / prefix
        _require("An installed project path is a symbolic link.", condition=not path.is_symlink())
        candidates = path.rglob("*") if path.is_dir() else (path,)
        for candidate in candidates:
            _require(
                "An installed project path is a symbolic link.",
                condition=not candidate.is_symlink(),
            )
            if candidate.is_file():
                observed.add(candidate.relative_to(root).as_posix())
    return observed


def _generated_installed(selected: SourceMap, root: Path) -> set[str]:
    if selected.record_path is None:
        message = "Installed payload checking requires a wheel source map."
        raise ArtifactError(message)
    metadata = PurePosixPath(selected.record_path).parent
    permitted = {(metadata / name).as_posix() for name in _INSTALLER_METADATA}
    permitted.update(
        Path(cache_from_source(str(root / item.distribution_path), optimization=optimization))
        .relative_to(root)
        .as_posix()
        for item in selected.files
        if item.distribution_path.endswith(".py")
        for optimization in _BYTECODE_OPTIMIZATIONS
    )
    return permitted


def verify_installed(selected: SourceMap, site_packages: Path) -> tuple[str, ...]:
    """Compare installed package files and explicitly classify installer records and bytecode.

    Source-derived bytecode names and qualified installer metadata are reported
    separately; their bytes are not claimed to be source-distribution bytes.
    Other distributions and generated command wrappers are outside this check.
    """
    _require("Installed checking requires a wheel map.", condition=selected.target is Target.WHEEL)
    site_packages = site_packages.resolve()
    expected = {item.distribution_path for item in selected.files}
    prefixes = {PurePosixPath(name).parts[0] for name in expected}
    observed = _installed_files(site_packages, prefixes)
    generated = observed - expected
    _require(
        "Installed project file set differs from the current source.",
        condition=expected <= observed
        and generated <= _generated_installed(selected, site_packages)
        and selected.record_path in observed,
    )
    for item in selected.files:
        _require(
            f"Installed payload size differs from the current source: {item.distribution_path}",
            condition=(site_packages / item.distribution_path).stat().st_size == item.size,
        )
        actual = _source(
            site_packages,
            site_packages / item.distribution_path,
            item.distribution_path,
            item.distribution_path,
        )
        _require(
            f"Installed payload differs from the current source: {item.distribution_path}",
            condition=(actual.sha256, actual.size) == (item.sha256, item.size),
        )
    return tuple(sorted(generated))
